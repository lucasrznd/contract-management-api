-- Initial schema, matching what Hibernate (ddl-auto=update) generated before Flyway was introduced.
-- Existing databases are baselined at version 1 (spring.flyway.baseline-on-migrate), so this script
-- only runs on empty databases.

CREATE TABLE tb_seller (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(255),
    phone_number VARCHAR(255),
    url_image    TEXT,
    CONSTRAINT tb_seller_pkey PRIMARY KEY (id)
);

CREATE TABLE tb_company (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    avenue_name         VARCHAR(255),
    business_name       VARCHAR(255),
    city                VARCHAR(255),
    cpf                 VARCHAR(255),
    email               VARCHAR(255),
    number              INTEGER,
    phone_number        VARCHAR(255),
    registration_number VARCHAR(255),
    state               VARCHAR(255),
    state_registration  VARCHAR(255),
    street_name         VARCHAR(255),
    trade_name          VARCHAR(255),
    zip_code            VARCHAR(255),
    CONSTRAINT tb_company_pkey PRIMARY KEY (id),
    CONSTRAINT uk6g1xorjokmkvquvxc7tmatn1g UNIQUE (trade_name),
    CONSTRAINT ukd8h17is5boq3b298m4qc95vm UNIQUE (business_name)
);

CREATE TABLE tb_contract (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    advertising_order       VARCHAR(255),
    end_date                DATE,
    flash_quantity          INTEGER NOT NULL,
    monthly_price           DOUBLE PRECISION,
    newspaper_participation VARCHAR(255),
    observation             VARCHAR(255),
    payment_due_day         INTEGER,
    payment_method          SMALLINT,
    pdf_path                TEXT,
    quantity_spot_day       INTEGER NOT NULL,
    spot_duration           DOUBLE PRECISION,
    start_date              DATE,
    testimonial_duration    DOUBLE PRECISION,
    testimonial_quantity    INTEGER NOT NULL,
    token                   TEXT,
    client_company_id       BIGINT,
    seller_id               BIGINT,
    CONSTRAINT tb_contract_pkey PRIMARY KEY (id),
    CONSTRAINT tb_contract_payment_method_check CHECK (payment_method >= 0 AND payment_method <= 1),
    CONSTRAINT fk7hccw4e7utc25b2xxt3udmmxc FOREIGN KEY (seller_id) REFERENCES tb_seller (id),
    CONSTRAINT fkkrgy7ot5uacdu5cq9aop431pc FOREIGN KEY (client_company_id) REFERENCES tb_company (id)
);
